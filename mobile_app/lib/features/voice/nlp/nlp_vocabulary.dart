  static int? monthNumber(String token) {
    final normalized = token.toLowerCase();
    for (var i = 0; i < _monthNames.length; i++) {
      final full = _monthNames[i];
      if (normalized == full ||
          normalized == full.substring(0, 3) ||
          normalized == '${full.substring(0, 3)}.') {
        return i + 1;
      }
    }
    if (normalized == 'sept') return 9;
    return null;
  }

